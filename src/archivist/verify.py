SHOWN_PROBLEMS = 6  # problems printed for one failed check; the rest are counted


@dataclass
class Result:
    status: str  # PASS, FAIL or SKIP
    name: str
    says: str  # one plain sentence: what was found
    problems: list[str] = field(default_factory=list)


def _first_difference(committed: bytes, fresh: bytes) -> str:
    """Where two texts first differ, for a person to find it."""
    old = committed.decode("utf-8", errors="replace").splitlines()
    new = fresh.decode("utf-8", errors="replace").splitlines()
    for number, (a, b) in enumerate(zip(old, new, strict=False), start=1):
        if a != b:
            return f"first difference at line {number}: committed {a[:70]!r}, regenerated {b[:70]!r}"
    return f"one has {len(old)} lines and the other {len(new)}"


# --- the test report -------------------------------------------------------------------------------


def check_test_report() -> list[Result]:
    """The report regenerated from the committed runs, byte for byte against the committed one."""
    committed = (test_report.OUT_JSON, test_report.OUT_MD)
    with tempfile.TemporaryDirectory() as scratch:
        fresh = tuple(Path(scratch) / path.name for path in committed)
        with (  # test_report.main writes to its module's paths: point them at the scratch folder
            mock.patch.object(test_report, "OUT_JSON", fresh[0]),
            mock.patch.object(test_report, "OUT_MD", fresh[1]),
            contextlib.redirect_stdout(io.StringIO()),  # main() prints its hypotheses
        ):
            test_report.main([])
        problems = []
        for path, regenerated in zip(committed, fresh, strict=True):
            if not path.exists():
                problems.append(f"{path} is missing")
            elif path.read_bytes() != regenerated.read_bytes():
                difference = _first_difference(path.read_bytes(), regenerated.read_bytes())
                problems.append(f"{path} is not what the committed runs score to: {difference}")
        hypotheses = json.loads(fresh[0].read_text(encoding="utf-8"))["hypotheses"]
    name = "Test report"
    if problems:
        return [Result(FAIL, name, "the committed report differs from a fresh scoring.", problems)]
    met = [h for h, verdict in hypotheses.items() if verdict["met"]]
    missed = [h for h in hypotheses if h not in met]
    says = (
        "regenerated from the committed runs, it is byte for byte the committed report "
        f"({len(met)} of {len(hypotheses)} pre-registered targets met: {', '.join(met) or 'none'}"
        + (f"; not met: {', '.join(missed)}" if missed else "")
        + ")."
    )
    return [Result(PASS, name, says)]


# --- the charts -------------------------------------------------------------------------------------


def check_charts() -> list[Result]:
    """docs/make_charts.py --check: the committed SVGs are what the report draws."""
    name = "Charts"
    if not CHARTS_SCRIPT.exists():
        return [Result(FAIL, name, f"{CHARTS_SCRIPT} is missing.", [f"{CHARTS_SCRIPT} is missing"])]
    done = subprocess.run(
        [sys.executable, str(CHARTS_SCRIPT), "--check"], capture_output=True, text=True
    )
    if done.returncode:
        lines = [line for line in (done.stdout + done.stderr).splitlines() if line.strip()]
        return [Result(FAIL, name, "a chart differs from the data.", lines[-SHOWN_PROBLEMS:])]
    return [Result(PASS, name, "the charts in docs/img are what the committed report draws.")]


# --- the exports ------------------------------------------------------------------------------------


def _committed_runs() -> list[str]:
    """Runs with a committed review bundle (data/bundles/index.json) or database (exports/)."""
    index = export_bundle.BUNDLES_DIR / export_bundle.INDEX_FILE
    runs = {r["run_id"] for r in json.loads(index.read_text(encoding="utf-8"))["runs"]}
    if database.EXPORTS_DIR.is_dir():
        runs |= {p.name for p in database.EXPORTS_DIR.iterdir() if p.is_dir()}
    return sorted(runs)


def _index_problems(built: Bundle) -> list[str]:
    """The run's entry in data/bundles/index.json, against the one a fresh export would write."""
    path = export_bundle.BUNDLES_DIR / export_bundle.INDEX_FILE
    entries = {r["run_id"]: r for r in json.loads(path.read_text(encoding="utf-8"))["runs"]}
    wanted = export_bundle.index_entry(built)
    if entries.get(built.run.run_id) != wanted:
        return [f"{path}: the entry for {built.run.run_id} differs from a fresh export's"]
    return []


def _missing_scan(error: FileNotFoundError) -> bool:
    """True when the file a build could not open is a Treasury scan, which is not committed."""
    return error.filename is not None and Path(error.filename).is_relative_to(
        export_bundle.REAL_PAGES
    )


def _dump(path: Path) -> str:
    """A SQLite database as text: its schema and every row, opened read-only."""
    with contextlib.closing(sqlite3.connect(f"{path.resolve().as_uri()}?mode=ro", uri=True)) as db:
        return "\n".join(db.iterdump())


def _database_problems(built: Bundle, exports: Path) -> list[str]:
    """Files in exports/<run> that differ from a fresh export, written to a scratch folder.

    The CSV files are compared byte for byte. The SQLite file is compared by its contents, not its
    bytes: its header and unused pages carry the version of the SQLite library that wrote it, so
    the same tables come out as different files on a different Python build (database --check
    compares bytes and fails there)."""
    problems = []
    with tempfile.TemporaryDirectory() as scratch:
        for fresh in database.write(built, Path(scratch)):
            on_disk = exports / fresh.name
            if not on_disk.exists():
                problems.append(f"{on_disk} is missing")
            elif fresh.suffix == ".sqlite":
                if _dump(on_disk) != _dump(fresh):
                    problems.append(f"{on_disk} holds different tables or rows than a fresh export")
            elif on_disk.read_bytes() != fresh.read_bytes():
                problems.append(f"{on_disk} differs from a fresh export of {built.run.run_id}")
    return problems


def _check_built(run_id: str, built: Bundle) -> list[Result]:
    out_dir = export_bundle.BUNDLES_DIR / run_id
    bundle_file = out_dir / export_bundle.BUNDLE_FILE
    problems = export_bundle.check(built, out_dir) + _index_problems(built)
    results = [
        Result(
            FAIL if problems else PASS,
            f"Review bundle, {run_id}",
            "valid, byte for byte a fresh export of the run, page images as recorded."
            if not problems
            else f"{bundle_file} does not match its run.",
            problems,
        )
    ]
    exports = database.EXPORTS_DIR / run_id
    if exports.is_dir():
        problems = _database_problems(built, exports)
        files = sum(1 for p in exports.iterdir() if p.is_file())
        results.append(
            Result(
                FAIL if problems else PASS,
                f"Database, {run_id}",
                f"{files} files match a fresh export of the run (CSVs byte for byte, "
                "SQLite row for row)."
                if not problems
                else f"{exports}/ does not match its run.",
                problems,
            )
        )
    return results


def _check_without_scans(run_id: str, error: FileNotFoundError) -> list[Result]:
    """A bundle whose scans are not here: it validates and its images match what it records,
    but it cannot be rebuilt, and that is said."""
    out_dir = export_bundle.BUNDLES_DIR / run_id
    bundle_file = out_dir / export_bundle.BUNDLE_FILE
    problems = []
    pages = 0
    try:
        recorded = Bundle.model_validate_json(bundle_file.read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        problems.append(f"{bundle_file} cannot be read as a bundle: {str(err)[:200]}")
    else:
        pages = len(recorded.pages)
        for page in recorded.pages:
            image = out_dir / page.image.url
            if not image.exists():
                problems.append(f"{image} is missing")
            elif hashlib.sha256(image.read_bytes()).hexdigest() != page.image.sha256:
                problems.append(f"{image} is not the image the bundle records")
    name = f"Review bundle, {run_id}"
    shown = (
        Result(FAIL, name, f"{bundle_file} is damaged.", problems)
        if problems
        else Result(
            PASS,
            name,
            f"valid, and its {pages} page images are as recorded (less than a rebuild; see below).",
        )
    )
    skipped = Result(
        SKIP,
        f"Rebuild of {run_id}",
        f"needs the Treasury Bulletin scans in {export_bundle.REAL_PAGES}/, which are not "
        "committed (python -m archivist.ingest.fraser fetches them); "
        f"{error.filename} is missing.",
    )
    return [shown, skipped]


def check_exports() -> list[Result]:
    """Each committed export, against a fresh export of its run."""
    results = []
    for run_id in _committed_runs():
        print(f"  building the export of {run_id} ...", flush=True)
        try:
            built = export_bundle.build(export_bundle.run_dir(run_id))
        except FileNotFoundError as error:
            if not _missing_scan(error):
                raise
            results += _check_without_scans(run_id, error)
        else:
            results += _check_built(run_id, built)
    return results


