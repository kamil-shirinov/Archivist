def run_checks(checks: Checks = CHECKS) -> list[Result]:
    """Every check, in order. One that cannot run counts as failed and says why; the rest run."""
    results = []
    for title, check in checks:
        print(f"Checking {title} ...", flush=True)
        started = time.monotonic()
        try:
            found = check()
        except (Exception, SystemExit) as error:  # the exporter and the report refuse by exiting
            found = [
                Result(
                    FAIL,
                    title.capitalize(),
                    "the check could not run.",
                    [f"{type(error).__name__}: {str(error)[:400]}"],
                )
            ]
        for result in found:
            print(f"  {result.status}  {result.name}", flush=True)
        print(f"  ({time.monotonic() - started:.0f} s)", flush=True)
        results += found
    return results


def summary(results: list[Result]) -> str:
    """What passed, what was skipped and why, what failed, then one line to end on."""
    by_status = {s: [r for r in results if r.status == s] for s in (PASS, SKIP, FAIL)}
    lines = ["", "Summary", ""]
    if by_status[PASS]:
        lines.append("What passed:")
        lines += [f"  - {r.name}: {r.says}" for r in by_status[PASS]]
    if by_status[SKIP]:
        lines += ["", "What could not be checked here:"]
        lines += [f"  - {r.name}: {r.says}" for r in by_status[SKIP]]
    if by_status[FAIL]:
        lines += ["", "What failed:"]
        for r in by_status[FAIL]:
            lines.append(f"  - {r.name}: {r.says}")
            lines += [f"      {problem}" for problem in r.problems[:SHOWN_PROBLEMS]]
            if len(r.problems) > SHOWN_PROBLEMS:
                lines.append(f"      ... and {len(r.problems) - SHOWN_PROBLEMS} more")
    counts = f"{len(by_status[PASS])} passed, {len(by_status[FAIL])} failed"
    counts += f", {len(by_status[SKIP])} not checked" if by_status[SKIP] else ""
    if by_status[FAIL]:
        verdict = f"NOT VERIFIED: {counts}."
    elif by_status[SKIP]:
        verdict = f"VERIFIED, EXCEPT WHAT IS LISTED AS NOT CHECKED: {counts}."
    else:
        verdict = f"VERIFIED: {counts}."
    return "\n".join([*lines, "", verdict, "No key, model call or response cache was used."])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.parse_args(argv)  # no options: it is the one command
    if not all(Path(marker).exists() for marker in ROOT_MARKERS):
        print("Run this from the repository root (the folder holding pyproject.toml).")
        return 2
    print(
        "Archivist: the checks that need no key, no response cache and no scans. "
        "Nothing is written to the repository.\n"
    )
    results = run_checks(CHECKS)
    print(summary(results))
    return 1 if any(r.status == FAIL for r in results) else 0


