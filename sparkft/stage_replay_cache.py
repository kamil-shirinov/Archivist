"""Stage only keys requested by the existing synthetic replay; never scan the shared cache.

Run once to prepare the isolated worktree, then run the owner's exact Check normally.
The temporary wrapper copies requested entries only and refuses absent entries before
any backend call. Existing replay fixes all backend caps at zero as a second guard.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import threading
from pathlib import Path

from archivist import replay
from archivist.models.cache import Cache, cache_key


def main():
    source = Path.cwd().parents[1] / 'cache'
    original = Cache._through
    staged = {}
    lock = threading.Lock()

    def stage(self, request, call, load):
        key = cache_key(self.name, self.model_id, request, self.settings)
        relative = Path(key[:2]) / (key + '.json')
        target = self.cache_dir / relative
        with lock:
            if not target.exists():
                src = source / relative
                # Only a key generated by the fixed synthetic replay is touched.
                if not src.is_file():
                    raise FileNotFoundError('Synthetic replay cache key missing: ' + key)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, target)
                staged[key] = hashlib.sha256(target.read_bytes()).hexdigest()
        return original(self, request, call, load)

    Cache._through = stage
    try:
        replay.main([])
    finally:
        Cache._through = original
        Path('results/scratch/sparkft/replay_cache_keys.json').write_text(
            json.dumps(staged, indent=2) + '\n')
        print('Synthetic replay cache entries staged:', len(staged))


if __name__ == '__main__':
    main()
